#!/usr/bin/env python3
"""Rebuild docs/decisions/INDEX.md from the records. Never edit the index by hand.

Usage: python3 scripts/decision-index.py [--check]
"""

import re
import sys
from pathlib import Path

DECISIONS = Path(__file__).resolve().parent.parent / "docs" / "decisions"
INDEX = DECISIONS / "INDEX.md"
NOT_A_RECORD = {"README.md", "INDEX.md", "_template.md"}
TITLE = re.compile(r"^#\s+(.+?)\s*$", re.MULTILINE)
DATE = re.compile(r"^-\s*\*\*Date:\*\*\s*(\d{4}-\d{2}-\d{2})", re.MULTILINE)


def read_records():
    records = []
    for path in DECISIONS.glob("*.md"):
        if path.name in NOT_A_RECORD:
            continue
        body = path.read_text(encoding="utf-8")
        title, date = TITLE.search(body), DATE.search(body)
        if not (title and date):
            sys.exit(
                f"docs/decisions/{path.name}: needs a '# Title' and a "
                "'- **Date:** YYYY-MM-DD' line (see _template.md)"
            )
        records.append((date[1], title[1], path.name))
    records.sort(key=lambda r: r[1])
    records.sort(key=lambda r: r[0], reverse=True)
    return records


def render(records):
    lines = [
        "<!-- Generated by scripts/decision-index.py. Do not edit by hand. -->",
        "",
        "# Decision index",
        "",
        "Every record, newest first. See [README](./README.md) for when and how to write one.",
        "",
        *(f"- [{title}](./{name}) — {date}" for date, title, name in records),
        "",
    ]
    return "\n".join(lines)


def main():
    expected = render(read_records())
    current = INDEX.read_text(encoding="utf-8") if INDEX.exists() else None
    if "--check" in sys.argv[1:]:
        if current != expected:
            sys.exit(
                "docs/decisions/INDEX.md is out of date. "
                "Run python3 scripts/decision-index.py"
            )
        return
    if current != expected:
        INDEX.write_text(expected, encoding="utf-8")
        print("docs/decisions/INDEX.md rebuilt")


if __name__ == "__main__":
    main()
